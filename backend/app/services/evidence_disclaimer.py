_TEMPLATES_BY_LANGUAGE = {
    "en": _EN_TEMPLATES,
    "bn": _BN_TEMPLATES,
}

# Shown when retrieval produced no case at all, so there is no top-1
# similarity to quote. Rendered as an em dash rather than "0.00", which
# would be a measurement that was never taken.
_NO_MEASUREMENT = "—"


def render_disclaimer(
    *,
    agreement: float | None,
    support: RetrievalSupport,
    top1_similarity: float | None,
    retrieval_floor: float,
    agreement_threshold: float,
    language: str,
) -> str:
    """S1 to S4: render the disclaimer from BOTH evidence signals.

    Keyword-only on purpose. Every parameter is a bare float and two of
    them (`agreement`, `top1_similarity`) are the two independent signals
    §7.1 forbids conflating -- positional arguments would make it possible
    to swap them at a call site and get a plausible-looking disclaimer
    computed from the wrong signal, with nothing to catch it.

    `agreement` is None when no label vote was possible (no retrieved
    cases). That is treated as low agreement: an absent vote is not
    evidence that the cases agree.
    """
    try:
        templates = _TEMPLATES_BY_LANGUAGE[language]
    except KeyError:
        # Same policy, same reasoning as ReportFormatter.format(): an
        # unexpected language code is a real bug worth surfacing, not
        # masking behind a silent English fallback that would put
        # mismatched text into a medical report.
        raise ValueError(
            f"unsupported language '{language}' -- expected one of "
            f"{sorted(_TEMPLATES_BY_LANGUAGE)}"
        ) from None

    # §7.1's Rule: the disclaimer must read BOTH signals. The matrix key
    # is (support, is_high_agreement) -- neither component is derived from
    # the other, which is §7's whole point.
    is_high_agreement = agreement is not None and agreement >= agreement_threshold
    template = templates[(support, is_high_agreement)]

    return template.format(
        top1=f"{top1_similarity:.2f}" if top1_similarity is not None else _NO_MEASUREMENT,
        floor=f"{retrieval_floor:.2f}",
        agreement=f"{agreement:.0%}" if agreement is not None else _NO_MEASUREMENT,
    )
