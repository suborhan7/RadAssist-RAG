"""
app/services/evidence_disclaimer.py
====================================================================
The evidence-support disclaimer -- §7 of
docs/methodology/input_admission_projection_gate_architecture_v1.1_FROZEN.md
(requirements S1 to S4, and §7.2's support matrix).

Why this module is NEW, when S3 says to use an existing template
----------------------------------------------------------------
S3 reads "Use the existing server-rendered parameterised template. Do not
add static text." No such template exists in this codebase, and this is
worth stating plainly rather than quietly working around: `disclaimer` is
one of the seven fields the LLM itself writes (REPORT_CONTENT_FIELDS in
prompt_builder.py), so up to now the disclaimer has been model-authored
free text, not server-rendered anything. A real generated example from
the Phase 7 dev log -- "Clinical uncertainty due to low agreement score
(0.60)" -- shows the shape of the problem exactly: it is prose the model
chose, and it reads ONE signal.

That single-signal reading is the specific failure §7.1's Warning
describes. Five retrieved cases can all sit below the retrieval floor and
still all carry the same label; agreement is then high, retrieval support
is low, and a disclaimer written from the agreement score alone announces
high confidence in what is actually weak evidence -- "the opposite of the
truth", in the document's words.

So S3's requirement is implemented, and only its "existing" is wrong
about this repository. The substance -- server-rendered, parameterised,
never static text, reading BOTH signals (§7.1's Rule) -- is what this
module provides, and building the template it names is not a change to
the architecture it is named in. The discrepancy is reported rather than
silently absorbed.

What replaces what
------------------
ReportGenerationService overwrites `content.disclaimer` with the output of
render_disclaimer() after generation. The LLM still emits a disclaimer
field (the 7-field output contract and its marker format are untouched,
and Phase 20 traced 17 real generation failures to that contract, so it is
not something to disturb for this); its text is simply not what reaches
the report. `disclaimer` was already AI-set-once and outside the five
doctor-editable fields (EditableReportField), so nothing a doctor can edit
changes hands here -- it moves from model-authored to server-authored,
which is the direction S3, S8 and S9 all point.

The parameters (S2)
-------------------
Exactly the two independent signals of §7.1, and nothing derived from
either: `agreement` (existing, `VotedLabel.agreement`) and
`support` (new, computed by ModalityGateService from the top-1 similarity
and the retrieval floor). The measured numbers are passed too, so the
rendered text can cite what was actually measured.

§7.2's closing Rule governs every string below: the disclaimer states
only what the measurement shows. The measurement shows that the top-1
similarity is below the configured floor. It does NOT show that the
archive holds no similar case -- a top-1 of 0.52 against a floor of 0.60
means a case exists and does not meet the threshold. No wording here may
be stronger than that, which is why every low-support string says "no
retrieved case meets the minimum retrieval-support threshold" and none
says the archive is empty of similar cases.
"""
